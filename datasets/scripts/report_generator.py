#!/usr/bin/env python3
"""
SafeBite AI - Report Generator Script
Compiles analysis, metadata, schema, inventory, and quality validation results
into 4 professional Markdown reports inside datasets/reports/:
1. 1_dataset_inventory.md
2. 2_schema_comparison.md
3. 3_data_quality_report.md
4. 4_dataset_summary.md
"""

import os
import sys
import json
import logging
import argparse
from pathlib import Path
from datetime import datetime

LOG_FORMAT = "%(asctime)s [%(levelname)s] %(name)s - %(message)s"

def setup_logging(log_file=None):
    logger = logging.getLogger("SafeBite.ReportGen")
    logger.setLevel(logging.INFO)
    logger.handlers.clear()
    
    c_handler = logging.StreamHandler(sys.stdout)
    c_handler.setFormatter(logging.Formatter(LOG_FORMAT))
    logger.addHandler(c_handler)
    
    if log_file:
        f_handler = logging.FileHandler(log_file, encoding='utf-8')
        f_handler.setFormatter(logging.Formatter(LOG_FORMAT))
        logger.addHandler(f_handler)
        
    return logger

def build_inventory_report(inventory_items: list, summary_info: dict, reports_dir: Path):
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    md = [
        "# 📊 SafeBite AI - Dataset Inventory Report",
        f"**Generated:** `{now_str}`  |  **Pipeline Version:** `1.0.0`",
        "",
        "> [!NOTE]",
        "> This inventory lists all discovered tabular food freshness datasets ingested into `datasets/raw/csv/`.",
        "",
        "## 📈 Summary Metrics",
        f"- **Total Indexed Datasets:** `{summary_info.get('total_datasets_indexed', 0)}`",
        f"- **Total Cumulative Rows:** `{summary_info.get('total_cumulative_rows', 0):,}`",
        f"- **Total Storage Size:** `{summary_info.get('total_storage_mb', 0.0)} MB`",
        f"- **Unique Columns Discovered:** `{summary_info.get('total_unique_columns_discovered', 0)}`",
        "",
        "## 📁 Dataset Catalog",
        "| Dataset ID | File Name | Size (MB) | Rows | Cols | Encoding | Delimiter | Location |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
    ]
    
    for item in inventory_items:
        ds_id = f"`{item['dataset_id']}`"
        fname = item["file_name"]
        size = item.get("file_size_mb", 0.0)
        rows = f"{item.get('total_rows', 0):,}"
        cols = item.get("total_columns", 0)
        enc = item.get("encoding", "utf-8")
        delim = f"`{item.get('delimiter', ',')}`"
        rel_path = f"`{item['relative_path']}`"
        
        md.append(f"| {ds_id} | `{fname}` | {size} MB | {rows} | {cols} | {enc} | {delim} | {rel_path} |")
        
    md.extend([
        "",
        "---",
        "*Automated report generated by SafeBite AI Data Engineering Pipeline.*"
    ])
    
    out_file = reports_dir / "1_dataset_inventory.md"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    return out_file

def build_schema_comparison_report(comp_info: dict, schemas_dir: Path, reports_dir: Path):
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    md = [
        "# 📐 SafeBite AI - Schema Comparison Report",
        f"**Generated:** `{now_str}`",
        "",
        "> [!IMPORTANT]",
        "> Evaluating feature compatibility and column overlaps across all raw datasets to prepare for future feature engineering.",
        "",
        "## 🔍 Overview",
        f"- **Total Datasets Compared:** `{comp_info.get('total_datasets_analyzed', 0)}`",
        f"- **Shared Feature Names Count:** `{len(comp_info.get('shared_columns', []))}`",
        "",
        "## 🔁 Shared Features Across Datasets",
        "The following columns appear in multiple datasets:" if comp_info.get('shared_columns') else "No overlapping column names detected yet.",
        ""
    ]
    
    if comp_info.get('shared_columns'):
        md.append("| Feature Name | Datasets Containing Feature |")
        md.append("| :--- | :--- |")
        for col in comp_info.get('shared_columns', []):
            freq = comp_info.get('column_frequency', {}).get(col, 0)
            md.append(f"| `{col}` | `{freq}` dataset(s) |")
            
    md.extend([
        "",
        "## 🔗 Dataset Pairwise Similarity (Jaccard Metric)",
        "| Dataset 1 | Dataset 2 | Shared Column Count | Jaccard Similarity | Shared Columns |",
        "| :--- | :--- | :--- | :--- | :--- |"
    ])
    
    pairs = comp_info.get("similarity_pairs", [])
    if pairs:
        for p in pairs:
            ds1 = p["dataset_1"]
            ds2 = p["dataset_2"]
            cnt = p["shared_column_count"]
            sim = p["jaccard_similarity"]
            scols = ", ".join([f"`{c}`" for c in p["shared_column_names"][:5]])
            if len(p["shared_column_names"]) > 5:
                scols += "..."
            md.append(f"| `{ds1}` | `{ds2}` | {cnt} | `{sim}` | {scols or 'None'} |")
    else:
        md.append("| N/A | N/A | 0 | 0.0 | None |")
        
    md.extend([
        "",
        "---",
        "*Automated report generated by SafeBite AI Data Engineering Pipeline.*"
    ])
    
    out_file = reports_dir / "2_schema_comparison.md"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    return out_file

def build_data_quality_report(val_info: dict, reports_dir: Path):
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    avg_score = val_info.get("overall_average_quality_score", 100.0)
    
    md = [
        "# 🛡️ SafeBite AI - Data Quality Report",
        f"**Generated:** `{now_str}`",
        "",
        f"> [!TIP]" if avg_score > 80 else "> [!WARNING]",
        f"> **Overall Dataset Quality Score:** `{avg_score}%`",
        "",
        "## ⚠️ Duplicate Datasets Audit",
        f"- **Duplicate Files Detected:** `{val_info.get('duplicate_datasets_count', 0)}`",
        ""
    ]
    
    dups = val_info.get("duplicate_datasets", [])
    if dups:
        md.append("| Original File | Duplicate File | MD5 Hash |")
        md.append("| :--- | :--- | :--- |")
        for d in dups:
            md.append(f"| `{d['original_file']}` | `{d['duplicate_file']}` | `{d['file_hash_md5']}` |")
    else:
        md.append("✅ No duplicate dataset files detected based on file hash audits.")
        
    md.extend([
        "",
        "## 📋 Individual Dataset Quality Audit",
        "| Dataset | Quality Score | Duplicate Rows | Missing Values | Empty Cols | Range Alerts |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |"
    ])
    
    for r in val_info.get("dataset_results", []):
        ds_name = r["file_name"]
        score = f"`{r['quality_score_pct']}%`"
        dups_info = f"{r['duplicate_rows_count']} ({r['duplicate_rows_pct']}%)"
        miss_info = f"{r['missing_values_total']} ({r.get('missing_values_pct', 0.0)}%)"
        empty_c = len(r.get("empty_columns", []))
        alerts_c = len(r.get("invalid_value_alerts", []))
        
        md.append(f"| `{ds_name}` | {score} | {dups_info} | {miss_info} | {empty_c} | {alerts_c} alert(s) |")
        
    md.extend([
        "",
        "---",
        "*Automated report generated by SafeBite AI Data Engineering Pipeline.*"
    ])
    
    out_file = reports_dir / "3_data_quality_report.md"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    return out_file

def build_dataset_summary_report(inventory_items: list, val_info: dict, comp_info: dict, reports_dir: Path):
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    md = [
        "# 📄 SafeBite AI - Executive Dataset Summary Report",
        f"**Generated:** `{now_str}`",
        "",
        "## 🌟 Executive Summary",
        "The SafeBite Data Engineering Pipeline successfully processed and validated raw data sources. This document outlines overall dataset readiness for feature engineering and ML modeling.",
        "",
        "## 📊 Core Statistics",
        f"- **Total Datasets Ingested:** `{len(inventory_items)}`",
        f"- **Average Quality Rating:** `{val_info.get('overall_average_quality_score', 0.0)}%`",
        f"- **Schema Overlap Index:** `{len(comp_info.get('shared_columns', []))} shared column(s)`",
        "",
        "## 🎯 Key Pipeline Recommendations",
        "1. **Non-Destructive Standard**: All raw files in `datasets/raw/` are preserved in pristine state.",
        "2. **Standardization Mapping**: Snake-case mapping dictionaries are pre-generated in `datasets/metadata/validation_results.json`.",
        "3. **Next Stage**: Prepare data cleaners in `processed/cleaned/` before proceeding to master dataset merging.",
        "",
        "---",
        "*Automated report generated by SafeBite AI Data Engineering Pipeline.*"
    ]
    
    out_file = reports_dir / "4_dataset_summary.md"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    return out_file

def generate_all_reports(metadata_dir: Path, schemas_dir: Path, reports_dir: Path, logger: logging.Logger = None):
    if logger is None:
        logger = setup_logging()
        
    metadata_dir = Path(metadata_dir).resolve()
    schemas_dir = Path(schemas_dir).resolve()
    reports_dir = Path(reports_dir).resolve()
    reports_dir.mkdir(parents=True, exist_ok=True)
    
    inventory_file = metadata_dir / "inventory.json"
    summary_file = metadata_dir / "inventory_summary.json"
    comp_file = schemas_dir / "schema_comparison.json"
    val_file = metadata_dir / "validation_results.json"
    
    inventory_items = []
    if inventory_file.exists():
        with open(inventory_file, "r", encoding="utf-8") as f:
            inventory_items = json.load(f)
            
    summary_info = {}
    if summary_file.exists():
        with open(summary_file, "r", encoding="utf-8") as f:
            summary_info = json.load(f)
            
    comp_info = {}
    if comp_file.exists():
        with open(comp_file, "r", encoding="utf-8") as f:
            comp_info = json.load(f)
            
    val_info = {}
    if val_file.exists():
        with open(val_file, "r", encoding="utf-8") as f:
            val_info = json.load(f)
            
    logger.info("Building 1_dataset_inventory.md...")
    build_inventory_report(inventory_items, summary_info, reports_dir)
    
    logger.info("Building 2_schema_comparison.md...")
    build_schema_comparison_report(comp_info, schemas_dir, reports_dir)
    
    logger.info("Building 3_data_quality_report.md...")
    build_data_quality_report(val_info, reports_dir)
    
    logger.info("Building 4_dataset_summary.md...")
    build_dataset_summary_report(inventory_items, val_info, comp_info, reports_dir)
    
    logger.info(f"All 4 reports successfully generated in {reports_dir}")

def main():
    parser = argparse.ArgumentParser(description="SafeBite Report Generator")
    parser.add_argument("--metadata-dir", default="datasets/metadata", help="Path to metadata directory")
    parser.add_argument("--schemas-dir", default="datasets/schemas", help="Path to schemas directory")
    parser.add_argument("--reports-dir", default="datasets/reports", help="Path to reports output directory")
    parser.add_argument("--log-file", default="datasets/metadata/pipeline.log", help="Path to log file")
    
    args = parser.parse_args()
    
    logger = setup_logging(args.log_file)
    logger.info("=== Starting Report Generation ===")
    
    generate_all_reports(args.metadata_dir, args.schemas_dir, args.reports_dir, logger=logger)

if __name__ == "__main__":
    main()
